def num(v: Any, digits: int = 2) -> str:
    if isinstance(v, (int, float)):
        return f"{v:.{digits}f}".rstrip("0").rstrip(".").replace(".", ",") if isinstance(v, float) else str(v)
    return str(v)


def term_rows(engine: FuzzyEngine, name: str, variant=None) -> List[List[str]]:
    rows = []
    for term, parts in engine.variables[name].term_set(variant).items():
        cores, supports = core_support(parts)
        core = " і ".join(f"{num(a)}…{num(b)}" if a != b else num(a) for a, b in cores)
        support = " і ".join(f"{num(a)}…{num(b)}" for a, b in supports)
        rows.append([f"**{term_ua(name, term)}** (`{term}`)", params_text(parts), core, support])
    return rows


