def rules_table(specs: List[Dict[str, Any]]) -> List[List[str]]:
    rows = []
    for spec in specs:
        rid = spec.get("id", "?")
        meta = spec.get("meta") or {}
        rows.append([f"**{rid}**", rule_ua(spec["rule"]), num(float(spec.get("weight", 1.0))),
                     WHY.get(rid, meta.get("rationale", ""))])
    return rows


